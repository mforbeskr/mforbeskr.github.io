// Generates the layered scenery in assets/scene/ and the scene markup in index.html.
// Run from anywhere with: node tools/gen-scene.mjs   (every layer shares one 2560x1440 canvas)
//
// Three scenes per theme, five layers each (sky, far, mid, near, front), named like night-2-mid.svg.
// Swapping in your own art: put a file with the same name and any image extension (night-2-mid.webp)
// in assets/scene/. The markup always uses whatever file exists for a layer, preferring a raster
// (webp, avif, png, jpg) over an SVG, and the generator never overwrites an SVG it did not write.
// Rasters should be 16:9 (2560x1440 is plenty) and transparent everywhere except in the sky layer.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(REPO, "assets/scene");
fs.mkdirSync(OUT, { recursive: true });

const W = 2560, H = 1440;
const MARK = "<!-- generated by tools/gen-scene.mjs -->";
const RASTER = ["webp", "avif", "png", "jpg", "jpeg"];

// The middle of the canvas is where the page's text sits, so the art frames it: tall things hug
// the sides (x < ~480, x > ~2080), the ground stays in the bottom fifth, and only soft sky, mist
// and the odd stray branch cross the middle.

function rng(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const f = (n) => +n.toFixed(1);
const pick = (r, arr) => arr[Math.floor(r() * arr.length)];
const lerp = (a, b, t) => a + (b - a) * t;
const pt = (p) => `${f(p[0])},${f(p[1])}`;

function wave(r, y, amps, step = 16, x0 = -120, x1 = W + 120) {
  const comps = amps.map(([a, wl]) => ({ a, k: (2 * Math.PI) / wl, p: r() * Math.PI * 2 }));
  const pts = [];
  for (let x = x0; x <= x1; x += step) {
    let yy = y;
    for (const c of comps) yy += c.a * Math.sin(c.k * x + c.p);
    pts.push([x, yy]);
  }
  return pts;
}

// Midpoint displacement: turns a few key points into a rough, natural outline.
function displace(r, keys, rough = 0.13, depth = 6) {
  let pts = keys.slice();
  for (let d = 0; d < depth; d++) {
    const out = [pts[0]];
    for (let i = 1; i < pts.length; i++) {
      const [ax, ay] = pts[i - 1], [bx, by] = pts[i];
      const len = Math.hypot(bx - ax, by - ay);
      out.push([(ax + bx) / 2 + (r() - 0.5) * len * rough, (ay + by) / 2 + (r() - 0.5) * len * rough * 2]);
      out.push(pts[i]);
    }
    pts = out;
  }
  return pts;
}

const area = (pts, bottom = H + 40) => `M${f(pts[0][0])},${bottom}L` + pts.map(pt).join("L") + `L${f(pts.at(-1)[0])},${bottom}Z`;
const line = (pts) => "M" + pts.map(pt).join("L");
const poly = (pts) => "M" + pts.map(pt).join("L") + "Z";
const box = (x, y, w, h) => `M${f(x)},${f(y)}h${f(w)}v${f(h)}h${f(-w)}Z`;
const circle = (x, y, r) => `M${f(x - r)},${f(y)}a${f(r)},${f(r)} 0 1,0 ${f(2 * r)},0a${f(r)},${f(r)} 0 1,0 ${f(-2 * r)},0`;

// An ellipse as path data, optionally turned by `rot` radians (so many can share one <path>).
function oval(x, y, rx, ry, rot = 0) {
  const c = Math.cos(rot) * rx, s = Math.sin(rot) * rx, deg = f((rot * 180) / Math.PI);
  return `M${f(x - c)},${f(y - s)}a${f(rx)},${f(ry)} ${deg} 1,0 ${f(2 * c)},${f(2 * s)}a${f(rx)},${f(ry)} ${deg} 1,0 ${f(-2 * c)},${f(-2 * s)}`;
}

function yAt(pts, x) {
  for (let i = 1; i < pts.length; i++) {
    if (pts[i][0] >= x) {
      const [ax, ay] = pts[i - 1], [bx, by] = pts[i];
      return ay + ((by - ay) * (x - ax)) / (bx - ax || 1);
    }
  }
  return pts.at(-1)[1];
}

// Points along a quadratic bezier.
function quad(a, c, b, n = 24) {
  return Array.from({ length: n + 1 }, (_, i) => {
    const t = i / n, u = 1 - t;
    return [u * u * a[0] + 2 * u * t * c[0] + t * t * b[0], u * u * a[1] + 2 * u * t * c[1] + t * t * b[1]];
  });
}

// A filled stroke along a polyline that narrows from w0 to w1 (trunks, stalks, branches).
function taper(pts, w0, w1) {
  const L = [], R = [];
  pts.forEach((p, i) => {
    const q = pts[Math.min(i + 1, pts.length - 1)], o = pts[Math.max(i - 1, 0)];
    const dx = q[0] - o[0], dy = q[1] - o[1], d = Math.hypot(dx, dy) || 1;
    const w = lerp(w0, w1, i / (pts.length - 1)) / 2;
    L.push([p[0] - (dy / d) * w, p[1] + (dx / d) * w]);
    R.push([p[0] + (dy / d) * w, p[1] - (dx / d) * w]);
  });
  return poly(L.concat(R.reverse()));
}

// A pointed leaf from (x, y) in direction a.
function leafPath(x, y, a, len, wid, bow = 0) {
  const ex = x + Math.cos(a) * len, ey = y + Math.sin(a) * len;
  const nx = -Math.sin(a), ny = Math.cos(a), mx = (x + ex) / 2 + nx * bow, my = (y + ey) / 2 + ny * bow;
  return `M${f(x)},${f(y)}Q${f(mx + nx * wid)},${f(my + ny * wid)} ${f(ex)},${f(ey)}Q${f(mx - nx * wid)},${f(my - ny * wid)} ${f(x)},${f(y)}Z`;
}

function maple(x, y, s, rot) {
  const pts = [];
  for (let i = 0; i < 10; i++) {
    const a = rot - Math.PI / 2 + (i * Math.PI) / 5;
    const rr = i % 2 ? s * 0.42 : s * (i === 4 || i === 6 ? 0.72 : 1);
    pts.push([x + Math.cos(a) * rr, y + Math.sin(a) * rr]);
  }
  return poly(pts);
}

function blade(x, base, h, w, bend) {
  return `M${f(x - w)},${f(base)}Q${f(x - w * 0.5 + bend * 0.5)},${f(base - h * 0.5)} ${f(x + bend)},${f(base - h)}Q${f(x + w * 0.5 + bend * 0.5)},${f(base - h * 0.5)} ${f(x + w)},${f(base)}Z`;
}

function grass(r, n, x0, x1, base, h, w = 2.4) {
  let d = "";
  for (let i = 0; i < n; i++) {
    const x = lerp(x0, x1, r()), b = base + r() * 14;
    for (let k = 0; k < 5; k++) d += blade(x + (r() - 0.5) * 18, b, h * (0.4 + r() * 0.8), w, (r() - 0.5) * h * 0.7);
  }
  return d;
}

// Bends angle a toward the direction (tx, ty) by k (0..1).
function steer(a, tx, ty, k) {
  return Math.atan2(Math.sin(a) * (1 - k) + ty * k, Math.cos(a) * (1 - k) + tx * k);
}

// A branching tree: returns the wood as one path and the branch ends (where foliage goes).
// o.up pulls branches skyward, o.flat pulls them level (Japanese pines).
function growTree(r, x, y, a, len, w, depth, o = {}) {
  const spread = o.spread ?? 0.5, shrink = o.shrink ?? 0.72, leafDepth = o.leafDepth ?? 2;
  let wood = "";
  const tips = [];
  (function grow(x, y, a, len, w, d) {
    const ex = x + Math.cos(a) * len, ey = y + Math.sin(a) * len;
    const bend = (r() - 0.5) * len * 0.35;
    const c = [(x + ex) / 2 - Math.sin(a) * bend, (y + ey) / 2 + Math.cos(a) * bend];
    const w2 = Math.max(w * shrink, 1.4);
    wood += taper(quad([x, y], c, [ex, ey], 6), w, w2);
    if (d <= leafDepth) tips.push([ex, ey]);
    if (d === 0) return;
    const n = r() < (o.fork3 ?? 0.3) ? 3 : 2;
    for (let k = 0; k < n; k++) {
      const off = n === 2 ? (k ? 1 : -1) * spread * (0.6 + r() * 0.6) : (k - 1) * spread * (0.8 + r() * 0.4);
      let na = a + off + (r() - 0.5) * 0.3;
      if (o.up) na = steer(na, 0, -1, o.up);
      if (o.flat) na = steer(na, Math.cos(na) >= 0 ? 1 : -1, -0.12, o.flat);
      if (o.lean) na = steer(na, o.lean[0], o.lean[1], o.lean[2]);
      grow(ex, ey, na, len * (0.68 + r() * 0.2), w2, d - 1);
    }
  })(x, y, a, len, w, depth);
  return { wood, tips };
}

// A leafy clump: a blob whose edge is scalloped into soft lobes.
function clump(r, x, y, rr, squash = 1) {
  const n = 2 * (5 + Math.floor(r() * 4)), pts = [], a0 = r() * Math.PI;
  for (let i = 0; i < n; i++) {
    const a = a0 + ((i + (r() - 0.5) * 0.7) / n) * Math.PI * 2, k = rr * (i % 2 ? 0.68 + r() * 0.2 : 0.92 + r() * 0.3);
    pts.push([x + Math.cos(a) * k, y + Math.sin(a) * k * squash]);
  }
  const mid = (i) => {
    const p = pts[i % n], q = pts[(i + 1) % n];
    return [(p[0] + q[0]) / 2, (p[1] + q[1]) / 2];
  };
  let d = `M${pt(mid(0))}`;
  for (let i = 1; i <= n; i++) d += `Q${pt(pts[i % n])} ${pt(mid(i))}`;
  return d + "Z";
}

// Foliage around branch ends, in four tones: shadow, body, lit side, and loose specks/petals.
// `light` points toward the light source; `squash` flattens clumps into pine-like pads.
function canopy(r, tips, size, tones, o = {}) {
  const light = o.light ?? [0.6, -0.8], squash = o.squash ?? 1, specks = o.specks ?? 0, shape = o.shape;
  const d = ["", "", "", ""], seen = new Set();
  for (const [x, y] of tips) {
    const cell = `${Math.round(x / (size * 0.8))},${Math.round(y / (size * 0.8))}`;
    if (seen.has(cell)) continue;
    seen.add(cell);
    const n = 2 + Math.floor(r() * 2);
    for (let k = 0; k < n; k++) {
      const rr = size * (0.5 + r() * 0.6), px = x + (r() - 0.5) * size * 1.8, py = y + (r() - 0.5) * size * squash;
      d[0] += clump(r, px - light[0] * rr * 0.12, py + rr * 0.2 * squash, rr * 1.08, squash);
      d[1] += clump(r, px, py, rr * 0.86, squash);
      if (r() < 0.55) d[2] += clump(r, px + light[0] * rr * 0.34, py + light[1] * rr * 0.34 * squash, rr * 0.42, squash);
    }
    for (let k = 0; k < specks; k++) {
      const a = r() * Math.PI * 2, dist = size * (0.9 + r() * 1.2);
      const sx = x + Math.cos(a) * dist * 1.3, sy = y + Math.sin(a) * dist * 0.8 * squash;
      d[3] += shape ? shape(sx, sy, 3 + r() * 5, r() * 6) : oval(sx, sy, 3 + r() * 3, 1.6 + r() * 1.4, r() * 3);
    }
  }
  return d.map((p, i) => (p ? `<path d="${p}" fill="${tones[i]}"/>` : "")).join("");
}

// A rough rock from a closed outline of key points; returns the outline points.
function rock(r, keys, rough = 0.14, depth = 5) {
  return displace(r, keys, rough, depth);
}

// One upturned temple roof, eaves at y.
function roof(cx, y, w, h) {
  const e = w / 2;
  return `M${f(cx - e)},${f(y - h * 0.4)}Q${f(cx - e * 0.86)},${f(y)} ${f(cx - e * 0.7)},${f(y)}L${f(cx + e * 0.7)},${f(y)}` +
    `Q${f(cx + e * 0.86)},${f(y)} ${f(cx + e)},${f(y - h * 0.4)}Q${f(cx + e * 0.45)},${f(y - h * 0.5)} ${f(cx + e * 0.2)},${f(y - h)}` +
    `L${f(cx - e * 0.2)},${f(y - h)}Q${f(cx - e * 0.45)},${f(y - h * 0.5)} ${f(cx - e)},${f(y - h * 0.4)}Z`;
}

// A tiered pagoda; returns the silhouette and its lit windows as [x, y, w, h].
function pagoda(r, cx, base, w, tiers, s) {
  let body = "";
  const lights = [];
  let y = base, tw = w;
  for (let t = 0; t < tiers; t++) {
    const wallH = s * (t === 0 ? 1.05 : 0.7), bw = tw * 0.52;
    body += box(cx - bw / 2, y - wallH, bw, wallH + 2) + box(cx - bw * 0.62, y - wallH * 0.12, bw * 1.24, s * 0.07);
    const n = Math.max(1, Math.round(bw / (s * 0.55)));
    for (let k = 0; k < n; k++) {
      if (r() < 0.45) continue;
      const ww = (bw / n) * 0.34;
      lights.push([cx - bw / 2 + (bw / n) * (k + 0.5) - ww / 2, y - wallH * 0.68, ww, wallH * 0.36]);
    }
    y -= wallH;
    body += roof(cx, y + s * 0.14, tw, s * 0.62);
    y -= s * 0.36;
    tw *= 0.82;
  }
  body += box(cx - s * 0.035, y - s * 1.1, s * 0.07, s * 1.15) + circle(cx, y - s * 1.12, s * 0.07);
  for (let k = 1; k <= 5; k++) body += box(cx - s * 0.11, y - s * 0.18 * k, s * 0.22, s * 0.04);
  return { body, lights };
}

function torii(cx, base, w, h) {
  const pw = w * 0.075, d = [];
  for (const side of [-1, 1]) {
    const xb = cx + side * w * 0.35, xt = cx + side * w * 0.32;
    d.push(poly([[xb - pw / 2, base], [xt - pw * 0.4, base - h * 0.9], [xt + pw * 0.4, base - h * 0.9], [xb + pw / 2, base]]));
  }
  d.push(`M${f(cx - w * 0.6)},${f(base - h)}Q${f(cx)},${f(base - h * 0.89)} ${f(cx + w * 0.6)},${f(base - h)}` +
    `L${f(cx + w * 0.53)},${f(base - h * 0.92)}Q${f(cx)},${f(base - h * 0.82)} ${f(cx - w * 0.53)},${f(base - h * 0.92)}Z`);
  d.push(box(cx - w * 0.47, base - h * 0.88, w * 0.94, h * 0.05));
  d.push(box(cx - w * 0.45, base - h * 0.7, w * 0.9, h * 0.045));
  d.push(box(cx - w * 0.03, base - h * 0.85, w * 0.06, h * 0.16));
  return d.join("");
}

// A stone lantern (tōrō); returns the stone and the lit window [x, y, w, h].
function toro(cx, base, s) {
  let d = poly([[cx - s * 0.45, base], [cx - s * 0.36, base - s * 0.16], [cx + s * 0.36, base - s * 0.16], [cx + s * 0.45, base]]);
  d += box(cx - s * 0.13, base - s * 0.85, s * 0.26, s * 0.7);
  d += poly([[cx - s * 0.36, base - s * 0.85], [cx - s * 0.3, base - s * 0.97], [cx + s * 0.3, base - s * 0.97], [cx + s * 0.36, base - s * 0.85]]);
  d += box(cx - s * 0.26, base - s * 1.4, s * 0.06, s * 0.44) + box(cx + s * 0.2, base - s * 1.4, s * 0.06, s * 0.44);
  d += box(cx - s * 0.26, base - s * 1.43, s * 0.52, s * 0.05) + box(cx - s * 0.26, base - s * 1.0, s * 0.52, s * 0.04);
  d += roof(cx, base - s * 1.38, s * 1.2, s * 0.36);
  d += circle(cx, base - s * 1.8, s * 0.09);
  return { stone: d, window: [cx - s * 0.2, base - s * 1.36, s * 0.4, s * 0.36] };
}

// A figure seen from behind, standing still or walking; the cloak is drawn separately so it can
// carry the scene's accent colour.
function ronin(x, base, h, hat) {
  const u = h / 10, P = (pts) => poly(pts.map(([a, b]) => [x + a * u, base - b * u]));
  const cloak = P([[-1.3, 7.5], [-1.75, 4.5], [-2.2, 0.7], [-1.0, 0.5], [1.1, 0.5], [2.05, 0.8], [1.7, 4.5], [1.3, 7.5], [0, 7.95]]);
  let body = P([[-0.8, 0.7], [-0.75, 0], [-0.15, 0], [-0.15, 0.7]]) + P([[0.2, 0.7], [0.25, 0], [0.85, 0], [0.8, 0.7]]);
  body += circle(x, base - 8.5 * u, 0.72 * u);
  body += hat ? P([[-2.6, 8.5], [0, 10.15], [2.6, 8.5], [0, 8.85]]) : circle(x + 0.15 * u, base - 9.35 * u, 0.36 * u);
  body += P([[-2.7, 2.6], [2.3, 5.4], [2.36, 5.24], [-2.64, 2.44]]);
  body += P([[-2.1, 3.25], [1.6, 5.05], [1.66, 4.9], [-2.04, 3.1]]);
  return { cloak, body };
}

// A palm: curved, ringed trunk and drooping fronds. Without a trunk it is just a crown of fronds
// (for palms leaning in from outside the frame).
function palm(r, base, top, o) {
  const len = o.len ?? 440, n = o.fronds ?? 12, fan = o.fan ?? 2.5;
  let back = "", fore = "", ribs = "", trunk = "";
  if (base) {
    const c = [base[0] + (top[0] - base[0]) * 0.2 + (o.bow ?? 0), base[1] + (top[1] - base[1]) * 0.55];
    const pts = quad(base, c, top, 40);
    trunk = `<path d="${taper(pts, o.w0 ?? 54, o.w1 ?? 28)}" fill="${o.trunk}"/>`;
    let rings = "";
    for (let i = 1; i < pts.length - 1; i++) {
      const [px, py] = pts[i], [qx, qy] = pts[i + 1], d = Math.hypot(qx - px, qy - py) || 1;
      const w = lerp(o.w0 ?? 54, o.w1 ?? 28, i / (pts.length - 1)) / 2, nx = (-(qy - py) / d) * w, ny = ((qx - px) / d) * w;
      rings += `M${f(px - nx)},${f(py - ny)}Q${f(px + (qx - px) * 0.8)},${f(py + (qy - py) * 0.8 + 4)} ${f(px + nx)},${f(py + ny)}`;
    }
    trunk += `<path d="${rings}" fill="none" stroke="${o.rings}" stroke-width="2.5" opacity=".55"/>`;
    trunk += `<path d="${taper(pts.map(([px, py]) => [px + 9, py]), (o.w0 ?? 54) * 0.25, (o.w1 ?? 28) * 0.2)}" fill="${o.shine}" opacity=".35"/>`;
  }
  for (let k = 0; k < n; k++) {
    const ang = -Math.PI / 2 + (k / (n - 1) - 0.5) * 2 * fan + (r() - 0.5) * 0.25 + (o.tilt ?? 0);
    const dir = [Math.cos(ang), Math.sin(ang)], L = len * (0.72 + r() * 0.4) * (1 - Math.max(0, -dir[1]) * 0.4);
    const end = [top[0] + dir[0] * L, top[1] + dir[1] * L * 0.45 + L * 0.5];
    const ctrl = [top[0] + dir[0] * L * 0.6, top[1] + dir[1] * L * 0.6 - L * 0.12];
    const spine = quad(top, ctrl, end, o.seg ?? 30);
    let d = "";
    for (let i = 2; i < spine.length; i++) {
      const t = i / (spine.length - 1), [px, py] = spine[i], [qx, qy] = spine[i - 1];
      const ta = Math.atan2(py - qy, px - qx), ll = L * 0.2 * Math.sin(Math.PI * Math.min(1, t * 1.1)) + 10;
      for (const side of [-1, 1]) {
        const la = ta + side * (0.85 + r() * 0.25);
        d += leafPath(px, py, Math.atan2(Math.sin(la) + 0.8, Math.cos(la)), ll * (0.85 + r() * 0.3), ll * 0.085);
      }
    }
    if (k % 2) fore += d; else back += d;
    ribs += line(spine);
  }
  let nuts = "";
  if (base && o.nuts) for (let i = 0; i < 4; i++) nuts += circle(top[0] + (r() - 0.5) * 40, top[1] + 14 + r() * 22, 12 + r() * 4);
  return `<path d="${back}" fill="${o.dark}"/>${trunk}${nuts && `<path d="${nuts}" fill="${o.nuts}"/>`}` +
    `<path d="${fore}" fill="${o.leaf}"/><path d="${ribs}" fill="none" stroke="${o.rib}" stroke-width="3" opacity=".7"/>`;
}

// A heaped cumulus cloud: shaded underside, body, sunlit tops.
function cumulus(r, cx, base, w, h, tones) {
  const bumps = [], n = Math.round(w / 45);
  for (let i = 0; i < n; i++) {
    const u = r(), x = cx + (u - 0.5) * w;
    const prof = Math.pow(Math.max(0, 1 - Math.pow(2 * u - 1, 2)), 0.7);
    const rr = 34 + prof * h * (0.22 + r() * 0.22);
    bumps.push([x, Math.min(base - prof * h * (0.3 + r() * 0.55), base - rr * 0.5), rr]);
  }
  let s = oval(cx, base - 10, w * 0.47, 46), m = "", l = "";
  for (const [x, y, rr] of bumps) {
    s += circle(x + rr * 0.08, y + rr * 0.2, rr);
    m += circle(x, y, rr * 0.9);
    l += circle(x - rr * 0.2, y - rr * 0.24, rr * 0.6);
  }
  return `<path d="${s}" fill="${tones[0]}"/><path d="${m}" fill="${tones[1]}"/><path d="${l}" fill="${tones[2]}"/>`;
}

// Short horizontal glints on water, crowded toward a reflection column at fx.
function glints(r, n, x0, x1, y0, y1, fx = null, fw = 0) {
  let d = "";
  for (let i = 0; i < n; i++) {
    const y = y0 + Math.pow(r(), 1.3) * (y1 - y0), p = (y - y0) / (y1 - y0);
    const x = fx !== null && r() < 0.6 ? fx + (r() - 0.5) * fw * (0.5 + p) : lerp(x0, x1, r());
    d += box(x, y, (8 + r() * 40) * (0.4 + p * 1.4), 1.2 + p * 2.6);
  }
  return d;
}

// Static stars go in the layer itself, the twinkling ones in its motion overlay.
function stars(L, r, n, y0, y1, color) {
  let dim = "", bright = "", tw = "";
  for (let i = 0; i < n; i++) {
    const x = r() * W, y = y0 + Math.pow(r(), 1.5) * (y1 - y0), s = 0.6 + Math.pow(r(), 3) * 1.9;
    if (r() < 0.7) dim += circle(x, y, s); else bright += circle(x, y, s);
  }
  for (let i = 0; i < 14; i++) {
    const x = r() * W, y = y0 + r() * (y1 - y0) * 0.6;
    tw += `<g class="tw" style="animation-delay:-${(r() * 6).toFixed(1)}s"><circle cx="${f(x)}" cy="${f(y)}" r="2.3"/>` +
      `<path d="M${f(x - 10)},${f(y)}h20M${f(x)},${f(y - 10)}v20" stroke="${color}" stroke-width=".9" opacity=".6"/></g>`;
  }
  L.add(`<path d="${dim}" fill="${color}" opacity=".45"/><path d="${bright}" fill="${color}" opacity=".9"/>`);
  L.animate(".tw{animation:tw 5s ease-in-out infinite alternate}@keyframes tw{from{opacity:.2}to{opacity:1}}", `<g fill="${color}">${tw}</g>`);
}

// ---------- One layer file ----------

class Layer {
  constructor(name) {
    this.name = name;
    this.defs = [];
    this.parts = [];
    this.css = "";
    this.motion = [];
    this.motionCss = "";
    this.cache = new Map();
  }
  grad(kind, stops, attrs = "") {
    const key = kind + JSON.stringify(stops) + attrs;
    if (!this.cache.has(key)) {
      const id = "g" + this.cache.size;
      const s = stops.map(([o, c, a = 1]) => `<stop offset="${o}" stop-color="${c}"${a < 1 ? ` stop-opacity="${a}"` : ""}/>`).join("");
      this.defs.push(`<${kind}Gradient id="${id}" ${attrs}>${s}</${kind}Gradient>`);
      this.cache.set(key, `url(#${id})`);
    }
    return this.cache.get(key);
  }
  // Top-to-bottom gradient in canvas coordinates
  vert(stops, y0 = 0, y1 = H) {
    return this.grad("linear", stops, `x1="0" y1="${f(y0)}" x2="0" y2="${f(y1)}" gradientUnits="userSpaceOnUse"`);
  }
  horiz(stops, x0 = 0, x1 = W, extra = "") {
    return this.grad("linear", stops, `x1="${f(x0)}" y1="0" x2="${f(x1)}" y2="0" gradientUnits="userSpaceOnUse"${extra}`);
  }
  // Fades out from the middle of whatever it fills
  soft(color, a = 1, inner = 0) {
    return this.grad("radial", [[inner, color, a], [1, color, 0]]);
  }
  blur(sd) {
    const key = "blur" + sd;
    if (!this.cache.has(key)) {
      const id = "b" + this.cache.size;
      this.defs.push(`<filter id="${id}" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="${sd}"/></filter>`);
      this.cache.set(key, `url(#${id})`);
    }
    return this.cache.get(key);
  }
  add(...s) {
    this.parts.push(...s);
    return this;
  }
  // Animated details live in a small overlay file (<name>-fx.svg) drawn over the layer, so the big
  // layer itself never has to be redrawn per frame; phones and reduced-motion visitors skip it.
  animate(css, ...s) {
    if (!this.motionCss.includes(css)) this.motionCss += css;
    this.motion.push(...s);
    return this;
  }
  path(d, fill, extra = "") {
    return this.add(`<path d="${d}" fill="${fill}"${extra}/>`);
  }
  fill(fill) {
    return this.add(`<rect x="-40" y="-40" width="${W + 80}" height="${H + 80}" fill="${fill}"/>`);
  }
  // A soft glow or wisp of mist
  puff(cx, cy, rx, ry, color, a, inner = 0, rot = 0) {
    const t = rot ? ` transform="rotate(${rot} ${f(cx)} ${f(cy)})"` : "";
    return this.add(`<ellipse cx="${f(cx)}" cy="${f(cy)}" rx="${f(rx)}" ry="${f(ry)}" fill="${this.soft(color, a, inner)}"${t}/>`);
  }
  // A level bank of mist, thickest in the middle
  band(y0, y1, color, a) {
    return this.add(`<rect x="-40" y="${f(y0)}" width="${W + 80}" height="${f(y1 - y0)}" fill="${this.vert([[0, color, 0], [0.5, color, a], [1, color, 0]], y0, y1)}"/>`);
  }
  // Mist rising from below: clear at y0, full from y1 down
  rise(y0, y1, color, a) {
    const b = H + 40;
    return this.add(`<rect x="-40" y="${f(y0)}" width="${W + 80}" height="${f(b - y0)}" fill="${this.vert([[0, color, 0], [(y1 - y0) / (b - y0), color, a], [1, color, a]], y0, b)}"/>`);
  }
  // Lit windows or openings, each with a halo
  lights(list, core, glow, a = 0.3) {
    let d = "";
    for (const [x, y, w, h] of list) {
      d += box(x, y, w, h);
      this.puff(x + w / 2, y + h / 2, w * 2.6 + 10, h * 2 + 10, glow, a);
    }
    return this.path(d, core);
  }
  // A paper lantern hanging from a cord
  lantern(x, y, s, cord, tones) {
    this.puff(x, y, s * 4.5, s * 4.5, tones.glow, 0.32);
    this.add(`<path d="M${f(x)},${f(y - s - cord)}V${f(y - s)}" stroke="${tones.cap}" stroke-width="${f(Math.max(1.5, s * 0.05))}"/>`);
    this.add(`<ellipse cx="${f(x)}" cy="${f(y)}" rx="${f(s * 0.76)}" ry="${f(s)}" fill="${this.grad("radial", [[0, tones.core], [0.55, tones.light], [1, tones.edge]], 'cx=".5" cy=".45" r=".6"')}"/>`);
    let ribs = "";
    for (let k = -3; k <= 3; k++) {
      const dy = k * s * 0.24, hw = s * 0.76 * Math.sqrt(Math.max(0, 1 - (dy / s) ** 2));
      ribs += `M${f(x - hw)},${f(y + dy)}Q${f(x)},${f(y + dy + s * 0.06)} ${f(x + hw)},${f(y + dy)}`;
    }
    this.add(`<path d="${ribs}" fill="none" stroke="${tones.edge}" stroke-width="${f(Math.max(1, s * 0.03))}" opacity=".45"/>`);
    return this.path(box(x - s * 0.42, y - s * 1.08, s * 0.84, s * 0.16) + box(x - s * 0.42, y + s * 0.92, s * 0.84, s * 0.16), tones.cap);
  }
  save() {
    const doc = (css, body, defs = "") =>
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" preserveAspectRatio="xMidYMax slice">` +
      `${MARK}<defs>${defs}</defs>${css ? `<style>${css}</style>` : ""}${body}</svg>\n`;
    write(`${this.name}.svg`, doc(this.css, this.parts.join(""), this.defs.join("")));
    if (this.motion.length) {
      write(`${this.name}-fx.svg`, doc(this.motionCss + "@media (prefers-reduced-motion:reduce){*{animation:none!important}}", this.motion.join("")));
    }
  }
}

// Writes a generated layer, unless your own art has taken its place.
function write(name, content) {
  const base = name.replace(/\.svg$/, ""), file = path.join(OUT, name);
  const own = RASTER.find((ext) => fs.existsSync(path.join(OUT, `${base}.${ext}`)));
  const handMade = fs.existsSync(file) && !fs.readFileSync(file, "utf8").includes(MARK);
  if (own || handMade) {
    if (own && fs.existsSync(file) && !handMade) fs.unlinkSync(file);
    console.log(name.padEnd(20), `kept your ${own ? `${base}.${own}` : "SVG"}`);
    return;
  }
  fs.writeFileSync(file, content);
  console.log(name.padEnd(20), (content.length / 1024).toFixed(1) + " KB");
}

