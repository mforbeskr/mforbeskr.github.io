// Aloe vera: a rosette of thick, tapering grey-green leaves, outer ones arching out.
function aloe(r, cx, base, s) {
  let back = "", fore = "", lit = "", teeth = "";
  const n = 13;
  for (let i = 0; i < n; i++) {
    const t = i / (n - 1), off = t - 0.5;
    const a = -Math.PI / 2 + off * 2.4 + (r() - 0.5) * 0.12, len = s * (0.7 + r() * 0.3) * (1 - Math.abs(off) * 0.45);
    const x = cx + off * s * 0.16, bow = off * s * 0.5, w = s * 0.085;
    const leaf = leafPath(x, base, a, len, w, bow);
    if (Math.abs(off) > 0.22) back += leaf; else fore += leaf;
    lit += leafPath(x + Math.cos(a + 1.57) * w * 0.3, base, a, len * 0.85, w * 0.3, bow);
    for (let k = 2; k < 8; k++) {
      const p = quad([x, base], [x + Math.cos(a) * len / 2 - Math.sin(a) * bow, base + Math.sin(a) * len / 2 + Math.cos(a) * bow], [x + Math.cos(a) * len, base + Math.sin(a) * len], 10)[k];
      teeth += circle(p[0] + Math.cos(a + 1.57) * w * 0.9, p[1] + Math.sin(a + 1.57) * w * 0.9, 1.6);
    }
  }
  return `<path d="${back}" fill="#7f9f86"/><path d="${fore}" fill="#93b39a"/><path d="${lit}" fill="#c3d8c4" opacity=".55"/><path d="${teeth}" fill="#eef3e8" opacity=".8"/>`;
}

// Sea buckthorn: slender grey stems, narrow silvery leaves and clusters of orange berries.
function buckthorn(r, x, base, h, n = 6) {
  let wood = "", leaves = "", leavesLit = "", berries = "", shine = "";
  for (let i = 0; i < n; i++) {
    const a = -Math.PI / 2 + (i / (n - 1) - 0.5) * 0.9 + (r() - 0.5) * 0.2, len = h * (0.7 + r() * 0.35);
    const end = [x + Math.cos(a) * len, base + Math.sin(a) * len];
    const pts = quad([x + (r() - 0.5) * 10, base], [x + Math.cos(a) * len * 0.5 + (r() - 0.5) * 60, base + Math.sin(a) * len * 0.5], end, 20);
    wood += taper(pts, 6, 1.5);
    for (let k = 4; k < pts.length; k++) {
      const [px, py] = pts[k], [qx, qy] = pts[k - 1], ta = Math.atan2(py - qy, px - qx), t = k / pts.length;
      for (const side of [-1, 1]) {
        if (r() < 0.25) continue;
        const la = ta + side * (0.45 + r() * 0.35);
        const leaf = leafPath(px, py, la, 26 + r() * 22, 2.6);
        if (r() < 0.5) leaves += leaf; else leavesLit += leaf;
      }
      if (t > 0.3 && t < 0.85 && r() < 0.7) {
        for (let b = 0; b < 4; b++) {
          const bx = px + (r() - 0.5) * 12, by = py + (r() - 0.5) * 12, br = 4 + r() * 2.5;
          berries += circle(bx, by, br);
          shine += circle(bx - br * 0.35, by - br * 0.35, br * 0.3);
        }
      }
    }
  }
  return `<path d="${wood}" fill="#8a7d70"/><path d="${leaves}" fill="#93a48c"/><path d="${leavesLit}" fill="#bccab3"/>` +
    `<path d="${berries}" fill="#ee9634"/><path d="${shine}" fill="#ffe0a8" opacity=".8"/>`;
}

